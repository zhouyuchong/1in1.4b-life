export function addExtraContent(age, data) {
  for (const [index, text] of (childhood[age] || []).entries()) data.events.push({ id: `childhood_${age}_${index}`, text, cashEffect: 0, effect: { sanity: 2, knowledge: 1 } });
  const spec = youthChoices[age] || (age >= 18 && age % 3 === 0 ? adultChoices[Math.floor(age / 3) % adultChoices.length] : null);
  if (spec && !data.choices.length) {
    const [title, description, options] = spec;
    data.choices.push({ id: `everyday_choice_${age}`, title, description, options: options.map((text, index) => ({ text, cashEffect: 0, effect: { sanity: index === 2 ? 4 : 3, knowledge: index === 2 ? 1 : 2 }, resultText: `你选择${text}。这个小小的决定，成为${age}岁值得记住的一段经历。` })) });
  }
  return data;
}
